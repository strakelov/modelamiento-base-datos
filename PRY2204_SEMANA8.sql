    id_tipo CHAR(3) CONSTRAINT TIPO_AUTOMOVIL_ID_NN NOT NULL,
    descripcion VARCHAR2(20) CONSTRAINT TIPO_AUTOMOVIL_DESCRIPCION_NN NOT NULL,
    CONSTRAINT TIPO_AUTOMOVIL_PK PRIMARY KEY (id_tipo)
