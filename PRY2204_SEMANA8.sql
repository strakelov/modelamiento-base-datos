    CONSTRAINT MANTENCION_AUTOMOVIL_FK FOREIGN KEY (patente_auto) REFERENCES AUTOMOVIL (patente),
    CONSTRAINT MANTENCION_MECANICO_FK FOREIGN KEY (cod_mecanico) REFERENCES MECANICO (cod_mecanico)
);

