CREATE TABLE CIUDAD (
    id_ciudad NUMBER(3) CONSTRAINT CIUDAD_ID_NN NOT NULL,
    nom_ciudad VARCHAR2(30) CONSTRAINT CIUDAD_NOMBRE_NN NOT NULL,
