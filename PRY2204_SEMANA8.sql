    telefono VARCHAR2(12),
    email VARCHAR2(40),
    tipo_cli CHAR(1) CONSTRAINT CLIENTE_TIPO_CLI_NN NOT NULL,
    CONSTRAINT CLIENTE_PK PRIMARY KEY (rut)
